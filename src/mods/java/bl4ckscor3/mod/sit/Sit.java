package bl4ckscor3.mod.sit;

import java.util.Arrays;
import net.minecraft.util.ResourceLocation;
import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.fml.common.ModMetadata;
import net.minecraftforge.fml.common.Mod.EventHandler;
import net.minecraftforge.fml.common.Mod.Instance;
import net.minecraftforge.fml.common.event.FMLInitializationEvent;
import net.minecraftforge.fml.common.event.FMLPreInitializationEvent;
import net.minecraftforge.fml.common.registry.EntityRegistry;

@Mod(
   modid = "sit",
   name = "Sit",
   version = "v1.3",
   acceptedMinecraftVersions = "[1.12.2]"
)
public class Sit {
   public static final String MODID = "sit";
   public static final String NAME = "Sit";
   public static final String VERSION = "v1.3";
   public static final String MC_VERSION = "1.12.2";
   @Instance("sit")
   public Sit instance;

   public Sit() {
   }

   @EventHandler
   public void preInit(FMLPreInitializationEvent event) {
      ModMetadata meta = event.getModMetadata();
      meta.authorList = Arrays.asList("bl4ckscor3");
      meta.autogenerated = false;
      meta.description = "Adds the ability to sit on slabs and stairs.";
      meta.modId = "sit";
      meta.name = "Sit";
      meta.version = "v1.3";
   }

   @EventHandler
   public void init(FMLInitializationEvent event) {
      EntityRegistry.registerModEntity(new ResourceLocation("sit", "entity_sit"), EntitySit.class, "entity_sit", 0, this.instance, 256, 20, false);
   }
}
